// vfwadd.vv with zero, subnormal, infinite and NaN operands, which the
// operand widening must convert exactly. Golden values from a Python model.

#include "vector_macros.h"

void TEST_CASE1(void) {
  VSET(16, e16, m2);
  VLOAD_16(v4, 0x0, 0x8000, 0x7c00, 0xfc00, 0x7e00, 0x1, 0x8001, 0x3c00, 0xbc00, 0x7bff, 0x1, 0x203, 0x3ff, 0x8005, 0x3a00, 0x3a00);
  VLOAD_16(v6, 0x0, 0x0, 0x3c00, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x1, 0x0);
  asm volatile("vfwadd.vv v8, v4, v6");
  VSET(16, e32, m4);
  VCMP_U32(1, v8, 0x0, 0x0, 0x7f800000, 0xff800000, 0x7fc00000, 0x33800000, 0xb3800000, 0x3f800000, 0xbf800000, 0x477fe000, 0x33800000, 0x3800c000, 0x387fc000, 0xb4a00000, 0x3f400001, 0x3f400000);
}

void TEST_CASE2(void) {
  VSET(16, e32, m2);
  VLOAD_32(v4, 0x0, 0x80000000, 0x7f800000, 0xff800000, 0x7fc00000, 0x1, 0x80000001, 0x3f800000, 0xbf800000, 0x7f7fffff, 0x1, 0x400003, 0x7fffff, 0x80000005, 0x3f400000, 0x3f400000);
  VLOAD_32(v6, 0x0, 0x0, 0x3f800000, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x1, 0x0);
  asm volatile("vfwadd.vv v8, v4, v6");
  VSET(16, e64, m4);
  VCMP_U64(2, v8, 0x0, 0x0, 0x7ff0000000000000, 0xfff0000000000000, 0x7ff8000000000000, 0x36a0000000000000, 0xb6a0000000000000, 0x3ff0000000000000, 0xbff0000000000000, 0x47efffffe0000000, 0x36a0000000000000, 0x38000000c0000000, 0x380fffffc0000000, 0xb6c4000000000000, 0x3fe8000000000000, 0x3fe8000000000000);
}

int main(void) {
  if (!snrt_is_spatz_core()) return 0;
  INIT_CHECK();
  enable_vec();
  enable_fp();

  TEST_CASE1();
  TEST_CASE2();

  EXIT_CHECK();
}
